from structure.plugin.pyspark import PySpark


def _recipe(transform):
    return Compiler.frontend.compile()(transform, materialize_schemas=False).lowered


def _source_schema_modules():
    from testing.model.orders.schemas.common import Address, AuditStamp, BusinessDate, TenantKey
    from testing.model.orders.schemas.customer import Customer
    from testing.model.orders.schemas.order import (
        OrderNormalized,
        OrderPublication,
        OrderPublished,
        OrderRaw,
        OrderWithCustomer,
        OrderWithProduct,
        OrderWithPromotion,
        PublicationFlags,
    )
    from testing.model.orders.schemas.product import Product
    from testing.model.orders.schemas.promotion import Promotion

    return {
        "testing.model.orders.schemas.common": [TenantKey, AuditStamp, Address, BusinessDate],
        "testing.model.orders.schemas.customer": [Customer],
        "testing.model.orders.schemas.order": [
            OrderRaw,
            OrderNormalized,
            OrderWithCustomer,
            OrderWithProduct,
            OrderWithPromotion,
            OrderPublication,
            PublicationFlags,
            OrderPublished,
        ],
        "testing.model.orders.schemas.product": [Product],
        "testing.model.orders.schemas.promotion": [Promotion],
    }


def test_v1_project_renderer_emits_runtime_schemas_transform_and_traceability() -> None:
    from testing.model.orders.transforms.order import EnrichOrders

    files = PySpark.render.project()(
        _recipe(EnrichOrders),
        source_transform="testing.model.orders.transforms.order.EnrichOrders",
        generated_package="testing.model.structure_generated.orders",
        source_schema_modules=_source_schema_modules(),
        traceability="compiler",
    )

    assert "testing/model/structure_generated/orders/runtime/schema_assert.py" in files
    assert "testing/model/structure_generated/orders/pyspark/schemas/order.py" in files
    assert "testing/model/structure_generated/orders/pyspark/transforms/testing/model/orders/transforms/order.py" in files
    assert (
        "testing/model/structure_generated/orders/traceability/transforms/"
        "testing/model/orders/transforms/order.EnrichOrders.json"
    ) in files

    transform = files["testing/model/structure_generated/orders/pyspark/transforms/testing/model/orders/transforms/order.py"]
    assert transform.startswith("# Generated by Structure. Do not edit by hand.\n")
    assert "from testing.model.structure_generated.orders.runtime.schema_assert import (" in transform
    assert "TransformResult," in transform
    assert "assert_schema," in transform
    assert "project_schema," in transform

    schema = files["testing/model/structure_generated/orders/pyspark/schemas/order.py"]
    assert "# Source: testing.model.orders.schemas.order" in schema
    assert (
        "ORDER_PUBLISHED_SCHEMA = T.StructType(ORDER_PUBLICATION_SCHEMA.fields + PUBLICATION_FLAGS_SCHEMA.fields)"
        in schema
    )

    traceability = json.loads(
        files[
            "testing/model/structure_generated/orders/traceability/transforms/"
            "testing/model/orders/transforms/order.EnrichOrders.json"
        ]
    )
    assert traceability["source_transform"] == "testing.model.orders.transforms.order.EnrichOrders"
    assert traceability["generated_transform_class"] == "EnrichOrdersGenerated"
    assert [step["name"] for step in traceability["steps"]] == [
        "normalize",
        "add_customer",
        "add_product",
        "add_promotion",
        "add_shipments",
        "publish",
    ]
    assert traceability["steps"][1]["joins"] == [
        {"how": "left", "input": "customer", "right_alias": "customers"},
    ]
    assert traceability["steps"][4]["after_hooks"] == ["note_lookup_inputs"]
    assert traceability["provenance"][0] == {
        "generated": (
            "generated:testing.model.structure_generated.orders.pyspark.transforms."
            "testing.model.orders.transforms.order.EnrichOrdersGenerated"
        ),
        "ir": "ir:EnrichOrders",
        "source": "source:testing.model.orders.transforms.order.EnrichOrders",
    }
    assert any(
        dependency["target"] == "OrderWithCustomer.customer_name"
        for dependency in traceability["static_dataflow"]["dependencies"]
    )
    assert {
        "hook": "add_quality_columns",
        "phase": "raw",
        "reason": "arbitrary PySpark hook body",
        "schema": "OrderPublished",
        "step": "publish",
        "target": "publish",
    } in traceability["static_dataflow"]["opaque_boundaries"]


