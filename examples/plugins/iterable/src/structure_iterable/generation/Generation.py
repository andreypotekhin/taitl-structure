from collections.abc import Mapping
from typing import cast

from structure.plugin.api.v1 import GenerationAPI as GenerationAPIV1
from structure.plugin.api.v1 import GenerationRequest, GenerationResult

from ..authoring.Authoring import BinaryStateExpression, LiteralStateExpression, StateExpression, StateValue
from ..compiler.Compiler import IterableRecipe


class Generation(GenerationAPIV1):
    """Renders finite Iterable recipes as standalone, loop-based Python source."""

    def generate(self, request: GenerationRequest) -> GenerationResult:
        if request.source_module is None or request.generated_package is None:
            raise ValueError("Iterable generation requires source-module and generated-package context.")
        recipes = cast(Mapping[str, IterableRecipe], request.payload)
        source = request.source_module.rsplit(".", 1)[1]
        module = f"{request.generated_package}.iterable.transforms.{source}"
        root = request.generated_package.replace(".", "/")
        path = module.replace(".", "/") + ".py"
        files = {
            f"{root}/__init__.py": "",
            f"{root}/iterable/__init__.py": "",
            f"{root}/iterable/transforms/__init__.py": "",
            path: self._module(recipes),
        }
        return GenerationResult(files, module, tuple(f"{recipe.name}Generated" for recipe in recipes.values()))

    def _module(self, recipes: Mapping[str, IterableRecipe]) -> str:
        lines = ["# Generated by Structure. Do not edit by hand.", ""]
        for recipe in recipes.values():
            lines.extend([f"class {recipe.name}Generated:", "    @staticmethod", "    def run(**inputs):"])
            for name in recipe.inputs:
                lines.append(f"        {name} = [dict(row) for row in inputs[{name!r}]]")
            sources = {name: name for name in recipe.inputs}
            for step in recipe.steps:
                for output in step.results:
                    lines.append(f"        {output} = []")
                if step.body.scan is not None:
                    initial = repr(step.body.scan.initial)
                    lines.extend([f"        _state = {initial}", "        for _ordinal, row in enumerate(" + sources[step.inputs[0]] + "):", "            if row.get('index') != _ordinal:", "                raise ValueError(\"Iterable scans require contiguous 'index' values starting at 0.\")"])
                    indent = "            "
                else:
                    lines.append(f"        for row in {sources[step.inputs[0]]}:")
                    indent = "            "
                for join in step.body.joins:
                    index = f"_{join.relation}_index"
                    lines.append(f"{indent}{index} = {{}}")
                    lines.append(f"{indent}for item in {sources[join.relation]}:")
                    lines.append(f"{indent}    {index}.setdefault(item.get({join.right.name!r}), []).append(item)")
                    fallback = "[{}]" if join.kind == "left" else "[]"
                    lines.append(f"{indent}for {join.relation} in {index}.get(row.get({join.left.name!r}), {fallback}):")
                    indent += "    "
                for output, projection in zip(step.results, step.body.projections, strict=True):
                    fields = ", ".join(
                        f"{self._column(projection.schema, name)!r}: {self._expression(value, driver=step.inputs[0])}"
                        for name, value in projection.values.items()
                    )
                    lines.append(f"{indent}{output}.append({{{fields}}})")
                    sources[output] = output
                if step.body.scan is not None:
                    next_state = ", ".join(self._state_expression(value) for value in step.body.scan.next)
                    lines.append(f"{indent}_state = ({next_state},)")
            if len(recipe.outputs) == 1:
                lines.append(f"        return {sources[recipe.outputs[0]]}")
            else:
                values = ", ".join(f"{name!r}: {sources[name]}" for name in recipe.outputs)
                lines.append(f"        return {{{values}}}")
            lines.append("")
        return "\n".join(lines)

    @staticmethod
    def _column(schema: object, name: str) -> str:
        return getattr(schema, "_structure_fields")[name].column

    @staticmethod
    def _expression(value: object, *, driver: str) -> str:
        if hasattr(value, "row") and hasattr(value, "name"):
            row, name = getattr(value, "row"), getattr(value, "name")
            return f"row.get({name!r})" if row == driver else f"{row}.get({name!r})"
        if isinstance(value, StateExpression):
            return Generation._state_expression(value)
        return repr(value)

    @staticmethod
    def _state_expression(value: StateExpression) -> str:
        if isinstance(value, StateValue):
            return f"_state[{value.ordinal}]"
        if isinstance(value, LiteralStateExpression):
            return repr(value.value)
        if isinstance(value, BinaryStateExpression) and value.operation == "add":
            return f"({Generation._state_expression(value.left)} + {Generation._state_expression(value.right)})"
        raise TypeError("Invalid Iterable scan state expression.")
